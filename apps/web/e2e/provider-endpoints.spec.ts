import { expect, test } from "@playwright/test";

test("supplier endpoints, searchable toggles, and protocol-scoped Solver options", async ({ page }, testInfo) => {
  const apiPort = process.env.TGA_PLAYWRIGHT_API_PORT ?? "18083";
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("/settings/models");
  await page.getByRole("button", { name: "添加供应商" }).click();
  await page.getByLabel("供应商名称", { exact: true }).fill("端点演示网关");
  await page.getByLabel("OpenAI Responses API 地址").fill(`http://127.0.0.1:${apiPort}/mock/responses/v1`);
  await page.getByRole("checkbox", { name: "Anthropic Messages" }).check();
  await page.getByLabel("Anthropic Messages API 地址").fill(`http://127.0.0.1:${apiPort}/mock/anthropic`);
  await page.getByLabel("API 密钥", { exact: true }).fill("e2e-placeholder-key");
  await page.screenshot({ path: testInfo.outputPath("create-provider.png"), fullPage: true });
  await page.getByRole("button", { name: "保存供应商" }).click();
  await expect(page.locator(".settings-message")).toContainText("已添加供应商");
  const responses = page.getByRole("region", { name: "OpenAI Responses 模型" });
  const anthropic = page.getByRole("region", { name: "Anthropic Messages 模型" });
  await expect(responses.getByRole("switch", { name: "启用 qwen-shared", exact: true })).not.toBeChecked();
  await responses.getByRole("switch", { name: "启用 qwen-shared", exact: true }).click();
  await expect(responses.getByRole("switch", { name: "启用 qwen-shared", exact: true })).toBeChecked();
  await page.getByRole("tab", { name: "Anthropic Messages", exact: true }).click();
  await expect(anthropic.getByRole("switch", { name: "启用 qwen-shared", exact: true })).not.toBeChecked();
  await anthropic.getByRole("switch", { name: "启用 anthropic-only", exact: true }).click();
  await expect(anthropic.getByRole("switch", { name: "启用 anthropic-only", exact: true })).toBeChecked();
  await page.getByRole("tab", { name: "OpenAI Responses", exact: true }).click();
  await responses.getByRole("searchbox").fill("SHARED");
  await expect(responses.getByRole("switch")).toHaveCount(1);
  await responses.getByRole("button", { expanded: true }).click();
  await expect(responses.getByRole("searchbox")).toHaveCount(0);
  await responses.getByRole("button", { expanded: false }).click();
  await responses.getByRole("searchbox").fill("");
  await responses.getByRole("button", { name: "读取可访问模型" }).click();
  await expect(page.locator(".settings-message")).toContainText("已有启用选择已保留");
  await expect(responses.getByRole("switch", { name: "启用 qwen-shared", exact: true })).toBeChecked();
  await page.reload();
  await page.getByRole("button", { name: /端点演示网关/ }).click();
  await expect(responses.getByRole("switch", { name: "启用 qwen-shared", exact: true })).toBeChecked();
  await page.screenshot({ path: testInfo.outputPath("models-desktop.png"), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto("/settings/solvers");
  await page.getByRole("button", { name: "配置 OpenAI Worker" }).click();
  let panel = page.getByLabel("OpenAI Worker Solver 配置", { exact: true });
  let select = panel.getByRole("combobox");
  await expect(select.getByRole("option", { name: "端点演示网关 / qwen-shared", exact: true })).toHaveCount(1);
  await expect(select.getByRole("option", { name: /anthropic-only|responses-only|disabled-model|Messages|Responses/ })).toHaveCount(0);
  await select.selectOption({ label: "端点演示网关 / qwen-shared" });
  await panel.getByRole("button", { name: "保存配置" }).click();
  await expect(page.locator(".settings-message")).toContainText("已保存");
  await page.getByRole("button", { name: "配置 Claude Worker" }).click();
  panel = page.getByLabel("Claude Worker Solver 配置", { exact: true });
  select = panel.getByRole("combobox");
  await expect(select.getByRole("option", { name: "端点演示网关 / anthropic-only", exact: true })).toHaveCount(1);
  await expect(select.getByRole("option", { name: "端点演示网关 / qwen-shared", exact: true })).toHaveCount(0);
  await select.selectOption({ label: "端点演示网关 / anthropic-only" });
  await panel.getByRole("button", { name: "保存配置" }).click();
  await expect(page.locator(".settings-message")).toContainText("已保存");
  await page.screenshot({ path: testInfo.outputPath("solver.png"), fullPage: true });
  await page.getByRole("button", { name: "配置 Reporter" }).click();
  await expect(page.getByLabel("Reporter Solver 配置", { exact: true }).getByRole("option", { name: "端点演示网关 / qwen-shared", exact: true })).toHaveCount(1);
  await page.getByLabel("Reporter Solver 配置", { exact: true }).getByRole("combobox").selectOption({ label: "端点演示网关 / qwen-shared" });
  await page.getByLabel("Reporter Solver 配置", { exact: true }).getByRole("button", { name: "保存配置" }).click();
  await expect(page.locator(".settings-message")).toContainText("已保存");
  await expect(page.getByRole("button", { name: "配置 Supervisor" })).toHaveCount(0);
  await page.getByRole("button", { name: "配置 Scout", exact: true }).click();
  const scoutPanel = page.getByLabel("Scout Solver 配置", { exact: true });
  await scoutPanel.getByRole("combobox").selectOption({ label: "端点演示网关 / qwen-shared" });
  await scoutPanel.getByRole("button", { name: "保存配置" }).click();
  await expect(page.locator(".settings-message")).toContainText("已保存");
  const created = await page.request.post("/api/v3/tasks", { multipart: { title: "三角色隔离验证", prompt: "Inspect local fixture only", scene_id: "cryptography" } });
  expect(created.ok()).toBe(true);
  const task = await created.json();
  const detail = await (await page.request.get(`/api/v3/tasks/${task.id}`)).json();
  expect(detail.agents.map((agent: { agent_id: string }) => agent.agent_id).sort()).toEqual(["reporter", "scout", "worker-claude", "worker-openai"]);
  await page.goto(`/tasks/${task.id}/runtime`);
  await expect(page.getByRole("button", { name: "查看 OpenAI Worker" })).toBeVisible();
  for (const name of [/Scout/, /OpenAI Worker/, /Claude Worker/, /Reporter/]) {
    await page.getByRole("button", { name: new RegExp("查看 " + name.source) }).click();
    await expect(page.getByRole("tab", { name: "活动", exact: true })).toBeVisible();
    await expect(page.getByRole("tab", { name: "对话", exact: true })).toHaveCount(0);
    await expect(page.getByPlaceholder(/添加提示/)).toHaveCount(0);
  }
  expect((await page.request.post(`/api/v3/tasks/${task.id}/prompts`, { data: { text: "removed" } })).status()).toBe(404);
  expect((await page.request.get(`/api/v3/tasks/${task.id}/events`)).ok()).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("three-agent-runtime.png"), fullPage: true });
  await page.request.delete(`/api/v3/tasks/${task.id}`);
  expect(errors).toEqual([]);
});
